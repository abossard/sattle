"""Extract the plotted nodes and edges from the bundled, final estate snapshots."""
import json
import math
from collections import deque
from pathlib import Path

HERE = Path(__file__).resolve().parent
ESTATE = HERE.parents[2] / "canvas/public/demo/estate"


def snapshot(name):
    return json.loads((ESTATE / f"{name}.final.snapshot.json").read_text())


def dimensions(graph):
    extent = graph["extent"]
    return {
        "revision": int(graph["descriptor"]["version"]["revision"]["value"]),
        "entities": len(extent["entities"]),
        "relationships": len(extent["relationships"]),
    }


def name(entity):
    properties = {
        p["property"]["value"].split(".")[-1]: p["value"]["value"]
        for p in entity["properties"] if "value" in p["value"]
    }
    for key in ("name", "meter", "host", "hostName", "eventId"):
        if key in properties:
            return properties[key].split("/microsoft.")[0]
    return entity["id"]["value"]


def distances(start, adjacent):
    lengths = {start: 0}
    queue = deque([start])
    while queue:
        node = queue.popleft()
        for neighbor in sorted(adjacent[node]):
            if neighbor not in lengths:
                lengths[neighbor] = lengths[node] + 1
                queue.append(neighbor)
    return lengths


def pod_layout(component, adjacent):
    """Fit the runtime network by its shortest-path distances (stress majorization)."""
    n = len(component)
    positions = [(math.cos(i * math.tau / n), math.sin(i * math.tau / n)) for i in range(n)]
    lengths = [distances(i, adjacent) for i in component]
    for _ in range(180):
        moved = []
        for i, (x, y) in enumerate(positions):
            tx = ty = weights = 0
            for j, (px, py) in enumerate(positions):
                if i == j:
                    continue
                desired = lengths[i][component[j]]
                weight = 1 / desired**2
                scale = desired / max(.0001, math.hypot(x - px, y - py))
                tx += weight * (px + (x - px) * scale)
                ty += weight * (py + (y - py) * scale)
                weights += weight
            moved.append((tx / weights, ty / weights))
        positions = moved
    xs, ys = zip(*positions)
    return [((x - min(xs)) / (max(xs) - min(xs)), (y - min(ys)) / (max(ys) - min(ys)))
            for x, y in positions]


def layout(nodes, edges):
    adjacent = [set() for _ in nodes]
    for a, b, _ in edges:
        adjacent[a].add(b)
        adjacent[b].add(a)
    pod = next(i for i, node in enumerate(nodes) if node[0] == "Pod")
    runtime = sorted(distances(pod, adjacent))
    cluster = nodes.index(["AzureResource", "aks-synth"])
    activity = sorted(set(distances(cluster, adjacent)) - {cluster})
    coordinates = {}
    for i, (x, y) in zip(runtime, pod_layout(runtime, adjacent)):
        coordinates[i] = ("runtime", x, y)
    coordinates[cluster] = ("activity", .5, .48)
    for j, i in enumerate(activity):
        angle = j * math.tau / len(activity) - math.pi / 2
        coordinates[i] = ("activity", .5 + .5 * math.cos(angle), .48 + .48 * math.sin(angle))
    pairs = sorted((nodes[b][1], a, b) for a, b, rel in edges
                   if rel == "MeterOf" and a not in coordinates)
    for row, (_, meter, resource) in enumerate(pairs):
        coordinates[meter] = ("meters", .15, row / (len(pairs) - 1))
        coordinates[resource] = ("meters", .85, row / (len(pairs) - 1))
    others = sorted(set(range(len(nodes))) - set(coordinates), key=lambda i: nodes[i])
    for j, i in enumerate(others):
        coordinates[i] = ("other", (j % 4) / 3, (j // 4) / max(1, (len(others) - 1) // 4))
    return [[*node, group, round(x, 4), round(y, 4)]
            for i, node in enumerate(nodes) for group, x, y in [coordinates[i]]]


def extract():
    master = snapshot("master")
    extent = master["extent"]
    nodes = extent["entities"]
    indices = {e["id"]["value"]: i for i, e in enumerate(nodes)}
    edges = [[indices[r["source"]["value"]], indices[r["target"]["value"]], r["type"]["value"]]
             for r in extent["relationships"]]
    return {
        "master": dimensions(master),
        "structure": dimensions(snapshot("workloadStructure")),
        "health": dimensions(snapshot("workload")),
        "nodes": layout([[e["type"]["value"], name(e)] for e in nodes], edges),
        "edges": edges,
    }


if __name__ == "__main__":
    data = extract()
    lines = [f"  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}" for k, v in data.items()]
    (HERE / "master-data.js").write_text(
        "// Generated by extract_master.py from the final Canvas estate snapshots.\n"
        + "const ShopMaster = {\n" + ",\n".join(lines) + "\n};\n"
    )
