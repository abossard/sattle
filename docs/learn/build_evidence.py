"""Extract the small evidence set used by the offline lesson from the Sattle checkout."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
ESTATE = ROOT / "engine/tests/Sattle.Tests/fixtures/estate"
EXPORT = ROOT / "canvas/public/demo/estate"


def records(path):
    return [json.loads(line) for line in path.read_text().splitlines() if line]


def evidence():
    resource_row = next(row["payload"] for row in records(ESTATE / "arg/resources.ndjson")
                     if row["payload"]["name"] == "pg-shop")
    readings = []
    for row in records(ESTATE / "azure-metrics/shop.ndjson"):
        if row["meta"]["resourceId"] == resource_row["id"]:
            meter = row["payload"]["value"][0]
            sample = meter["timeseries"][0]["data"][0]
            readings.append(dict(minute=sample["timeStamp"][11:16], value=sample["average"],
                                 received=row["capturedAt"][11:19], meter=meter["name"]["value"]))
    rule = next(row["payload"] for row in records(ESTATE / "authoring/rules.ndjson")
                if row["payload"]["id"] == "database-down")
    # Reconstruct component states from the empty revision-zero graph and its actual edits.
    snapshot = json.loads((EXPORT / "workload.snapshot.json").read_text())
    assert not snapshot["extent"]["entities"]
    states, revisions = {}, []
    for patch in records(EXPORT / "workload.patches.ndjson"):
        for edit in patch["edits"]:
            if edit["kind"] != "entity":
                continue
            key = edit["id"]["value"]
            if edit["after"] is None:
                states.pop(key, None)
                continue
            props = {p["property"]["value"].split(".")[-1]: p["value"].get("value")
                     for p in edit["after"]["properties"]}
            if props.get("kind") in {"workload", "service", "resource", "gateway"}:
                states[key] = (props["name"], props.get("state", "Unknown"))
        revisions.append(dict(revision=int(patch["to"]["revision"]["value"]), states=dict(states.values())))
    return dict(resourceId=resource_row["id"], readings=readings, rule=rule, revisions=revisions)


if __name__ == "__main__":
    payload = json.dumps(evidence(), indent=2, ensure_ascii=False)
    (HERE / "replay-data.js").write_text("// Generated by build_evidence.py from the estate fixture and Canvas export.\n"
                                         + "const replay = " + payload + ";\n")
