"""Replay the same shop twice. Add one API deployment update to the second recording."""
import json
import shutil
import subprocess
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
ENGINE = ROOT / "engine/src/Sattle.Cli/bin/Release/net11.0/sattle.dll"
ESTATE = ROOT / "engine/tests/Sattle.Tests/fixtures/estate"


def fields(node):
    return {p["property"]["value"].split(".")[-1]: p["value"]["value"] for p in node["properties"]}


def result_at(capture, output, target="shopcache"):
    until = "2026-01-01T10:06:30Z"
    subprocess.run(["dotnet", str(ENGINE), "replay", str(capture), "--cluster", "synth",
                    "--until", until, "--out", str(output)], cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
    def entities(graph):
        snapshot = json.loads((output / f"{graph}.final.snapshot.json").read_text())
        return [fields(e) for e in snapshot["extent"]["entities"]]
    selected = {"shop", "web", "api", "database", "pg-shop", "shopcache", "shopassets", "apim-shop"}
    states = {e["name"]: e["state"] for e in entities("workload")
              if e.get("name") in selected | {target} and e.get("kind") in {"workload","service","resource","gateway"}}
    supports = [e["detail"] for e in entities("workloadStructure") if e.get("sourceKey") == "svc/synth/shop/api"
                and e.get("targetKey","").endswith("/"+target) and e.get("how") == "configuration"]
    return dict(cutoff=until, states=states, configurationEvidence=supports)


def main():
    with tempfile.TemporaryDirectory(prefix="sattle-lesson-") as staging:
        temp = Path(staging)
        changed = temp / "estate"
        shutil.copytree(ESTATE, changed)
        watch = changed / "kubernetes/watch.ndjson"
        events = [json.loads(line) for line in watch.read_text().splitlines()]
        event = next(e for e in events if e["payload"].get("object",{}).get("kind") == "Deployment"
                     and e["payload"]["object"]["metadata"]["name"] == "api")
        event.update(capturedAt="2026-01-01T10:04:00.000Z", seq=max(e["seq"] for e in events)+1,
                     key="kubernetes-watch/MODIFIED/Deployment/dep-api/990")
        event["payload"]["type"] = "MODIFIED"
        obj = event["payload"]["object"]
        obj["metadata"]["resourceVersion"] = "990"
        obj["spec"]["template"]["spec"]["containers"][0]["env"].append(
            dict(name="CACHE_HOST", value="shopcache.redis.cache.windows.net"))
        # A separate source file preserves time order within the original watch file.
        (changed / "kubernetes/lesson-change.ndjson").write_text(json.dumps(event)+"\n")
        before = result_at(ESTATE, temp/"before")
        after = result_at(changed, temp/"after")
        assert before["states"]["api"] == "Healthy" and after["states"]["api"] == "Degraded"
        assert not before["configurationEvidence"] and after["configurationEvidence"]
        # A second counterfactual: the API names a cache before Azure inventory reports it.
        host = "offers-cache.redis.cache.windows.net"
        obj["spec"]["template"]["spec"]["containers"][0]["env"][-1]["value"] = host
        (changed / "kubernetes/lesson-change.ndjson").write_text(json.dumps(event)+"\n")
        waiting = result_at(changed, temp/"waiting", "offers-cache")
        inventory = next(json.loads(line) for line in (changed/"arg/resources.ndjson").read_text().splitlines()
                         if json.loads(line)["payload"]["name"] == "shopcache")
        inventory["payload"]["name"] = "offers-cache"
        inventory["payload"]["id"] = inventory["payload"]["id"].removesuffix("shopcache")+"offers-cache"
        inventory.update(capturedAt="2026-01-01T10:05:00.000Z", seq=990, key="arg/resources/"+inventory["payload"]["id"])
        (changed/"arg/lesson-cache.ndjson").write_text(json.dumps(inventory)+"\n")
        discovered = result_at(changed, temp/"discovered", "offers-cache")
        assert not waiting["configurationEvidence"] and "offers-cache" not in waiting["states"]
        assert discovered["configurationEvidence"] and discovered["states"]["offers-cache"] == "Unknown"
        result = {"original": before, "changed": after, "waiting": waiting, "discovered": discovered}
        (HERE / "change-data.js").write_text("// Generated by replay_change.py from two engine runs.\nconst changeResult = "
                                             +json.dumps(result, indent=2)+";\n")
        print(json.dumps(result,indent=2))


if __name__ == "__main__":
    main()
